"""Generates docs/SETTINGS.md from the settings declared in src/baritone/Settings.h.

    python tools/gen_settings_doc.py

Run it after adding or changing a setting so the documentation stays in sync.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src" / "baritone" / "Settings.h"
OUTPUT = ROOT / "docs" / "SETTINGS.md"

ENTRY = re.compile(r'X\(\s*([\w:<>]+)\s*,\s*(\w+)\s*,\s*(.*?)\s*,\s*"((?:[^"\\]|\\.)*)"\s*\)')
CONTINUATION = re.compile(r"\\[ \t]*\r?\n\s*")

TYPE_NAMES = {
    "bool": "boolean",
    "int": "integer",
    "int64_t": "integer",
    "double": "decimal",
    "float": "decimal",
    "std::string": "text",
    "BlockList": "block list",
    "ItemList": "item list",
    "StringList": "text list",
    "Color": "color (r,g,b)",
}


def pretty_default(kind: str, value: str) -> str:
    value = value.strip()
    if value.startswith("(") and value.endswith(")"):
        value = value[1:-1].strip()
    if re.fullmatch(r"\w+\(\)", value) or value in ("{}", '""', "std::string()"):
        return "*(empty)*"
    if kind == "Color":
        return ",".join(re.findall(r"-?\d+", value))
    if kind in ("BlockList", "ItemList", "StringList"):
        items = re.findall(r'"([^"]*)"', value)
        return ", ".join(items) if items else "*(empty)*"
    if kind == "std::string":
        m = re.fullmatch(r'"(.*)"', value)
        return m.group(1) if m else value
    value = value.rstrip("f") if re.fullmatch(r"-?\d+\.\d*f", value) else value
    return value


def main() -> None:
    text = CONTINUATION.sub(" ", SOURCE.read_text(encoding="utf-8"))  # join the macro's lines
    rows = ENTRY.findall(text)
    lines = [
        "# Settings",
        "",
        "<!-- Generated by tools/gen_settings_doc.py from src/baritone/Settings.h. Do not edit by hand. -->",
        "",
        "Every setting has the same name, default value and meaning as in "
        "[Baritone's Settings.java](https://github.com/cabaletta/baritone/blob/master/src/api/java/baritone/api/Settings.java), "
        "so guides written for Baritone apply here. "
        "Differences that come from Bedrock are listed in [PARITY.md](PARITY.md).",
        "",
        "Usage in the chat:",
        "",
        "```",
        "#set <name> <value>     change a setting (#set allowBreak false)",
        "#set <name>             show a setting; a boolean is toggled",
        "#set reset <name|all>   back to the default",
        "#modified               list the settings you changed",
        "```",
        "",
        "Lists are written comma-separated (`#set blocksToAvoid minecraft:magma,minecraft:cactus`), "
        "colors as `r,g,b`. Changed settings are saved to `%LOCALAPPDATA%\\BaritoneBedrock\\settings.txt` "
        "and loaded again on the next injection.",
        "",
        f"{len(rows)} settings.",
        "",
        "| Setting | Type | Default | Description |",
        "|---|---|---|---|",
    ]
    for kind, name, default, desc in rows:
        shown = pretty_default(kind, default)
        shown = shown if shown == "*(empty)*" else f"`{shown}`"
        lines.append(f"| `{name}` | {TYPE_NAMES.get(kind, kind)} | {shown} | {desc} |")
    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(rows)} settings)")


if __name__ == "__main__":
    main()
